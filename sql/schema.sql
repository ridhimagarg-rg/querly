CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL, email VARCHAR(180) UNIQUE NOT NULL,
    phone VARCHAR(30), password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'patient', is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS hospitals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(180) NOT NULL, address VARCHAR(255) NOT NULL, city VARCHAR(80) NOT NULL,
    phone VARCHAR(30), email VARCHAR(180)
);
CREATE TABLE IF NOT EXISTS departments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hospital_id INTEGER NOT NULL REFERENCES hospitals(id), name VARCHAR(120) NOT NULL, description TEXT
);
CREATE TABLE IF NOT EXISTS doctors (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER UNIQUE NOT NULL REFERENCES users(id), hospital_id INTEGER NOT NULL REFERENCES hospitals(id),
    department_id INTEGER NOT NULL REFERENCES departments(id), specialization VARCHAR(120) NOT NULL,
    consultation_fee DOUBLE PRECISION NOT NULL DEFAULT 500, is_available BOOLEAN NOT NULL DEFAULT TRUE,
    weekly_schedule JSONB, qualification VARCHAR(200), experience_years INTEGER DEFAULT 5, bio TEXT
);
CREATE TABLE IF NOT EXISTS slots (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id INTEGER NOT NULL REFERENCES doctors(id), date DATE NOT NULL, start_time TIME NOT NULL, end_time TIME NOT NULL,
    max_patients INTEGER NOT NULL DEFAULT 10, booked_count INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_doctor_slot UNIQUE (doctor_id, date, start_time)
);
CREATE TABLE IF NOT EXISTS appointments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id INTEGER NOT NULL REFERENCES users(id), doctor_id INTEGER NOT NULL REFERENCES doctors(id),
    slot_id INTEGER NOT NULL REFERENCES slots(id), appointment_date DATE NOT NULL, appointment_time TIME NOT NULL,
    token_no VARCHAR(30), status VARCHAR(30) NOT NULL DEFAULT 'booked', symptoms TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS queue (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER UNIQUE NOT NULL REFERENCES appointments(id), patient_id INTEGER NOT NULL REFERENCES users(id),
    doctor_id INTEGER NOT NULL REFERENCES doctors(id), token_no VARCHAR(30) NOT NULL, queue_position INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'waiting', checked_in_time TIMESTAMPTZ, called_time TIMESTAMPTZ, completed_time TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS e_slips (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER UNIQUE NOT NULL REFERENCES appointments(id), qr_payload TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS consultations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER UNIQUE NOT NULL REFERENCES appointments(id), doctor_id INTEGER NOT NULL REFERENCES doctors(id),
    notes TEXT, diagnosis TEXT, prescription TEXT, consultation_datetime TIMESTAMPTZ NOT NULL DEFAULT NOW(), followup_date DATE
);
CREATE TABLE IF NOT EXISTS notifications (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(id), type VARCHAR(50), message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS payments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER NOT NULL REFERENCES appointments(id), amount DOUBLE PRECISION NOT NULL,
    payment_mode VARCHAR(30) NOT NULL DEFAULT 'cash', payment_status VARCHAR(30) NOT NULL DEFAULT 'pending',
    payment_date TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS feedback (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id INTEGER NOT NULL REFERENCES appointments(id), rating INTEGER NOT NULL, comment TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS patient_profiles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER UNIQUE NOT NULL REFERENCES users(id), date_of_birth DATE, sex VARCHAR(20), blood_group VARCHAR(10),
    address VARCHAR(255), city VARCHAR(80), emergency_contact_name VARCHAR(120), emergency_contact_phone VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS audit_logs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES users(id), action VARCHAR(100) NOT NULL, entity VARCHAR(100) NOT NULL, entity_id INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
